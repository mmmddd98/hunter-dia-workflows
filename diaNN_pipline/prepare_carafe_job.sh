normalize_staged_report() {
  local staged_report="$INPUT_DIR/diann_step2_report.parquet"
  # A report can be symlinked for a non-shared job. Replace only the job input,
  # never the source DIA-NN report, before changing its schema.
  if [[ -L "$staged_report" ]]; then
    local local_copy="$INPUT_DIR/.diann_step2_report.parquet.normalize.$$"
    cp -pL "$staged_report" "$local_copy"
    mv -f "$local_copy" "$staged_report"
  fi
  "${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/normalize_carafe_report.py" --report "$staged_report"
}

stage_normalized_report() {
  local staged_report="$INPUT_DIR/diann_step2_report.parquet"
  [[ ! -e "$staged_report" && ! -L "$staged_report" ]] || die "Refusing to replace an existing staged report: $staged_report. Create a new job name for a fresh preparation."
  if [[ "$ENTRAPMENT_SOURCE" == "1" && "$INCLUDE_ENTRAPMENT_HITS" != "1" ]]; then
    "${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/filter_carafe_entrapment_report.py" \
      --source "$REPORT" \
      --destination "$staged_report" \
      --fasta "$FASTA" \
      --stats "$JOB_DIR/meta/entrapment_filter.json"
  else
    "${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/normalize_carafe_report.py" \
      --source "$REPORT" --destination "$staged_report"
  fi
}

