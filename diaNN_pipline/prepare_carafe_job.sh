#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PIPELINE_ROOT="$SCRIPT_DIR"

usage() {
  cat <<'EOF'
Usage:
  bash prepare_carafe_job.sh --source-exp <existing_experiment> --profile <balanced|fast|slow> [options]

Prepare a portable Carafe 2 GPU job from an existing DIA-NN pipeline run.
The source experiment is read only. Only its Step-2 training mzML files are
staged; test mzML files are recorded in the manifest but never staged.

By default, the job is written to
<source-experiment>/carafe/<profile>/<job_name>. It includes generated
scripts to transfer portable inputs to a GPU PC and return Carafe results.

Required:
  --source-exp <name>          Existing DIA-NN experiment name
  --profile <name>             balanced, fast, or slow

Options:
  --name <job_name>            Job name below carafe/<profile> (default: carafe)
  --pipeline-version <version> Source version directory, e.g. 2_5_0 (default: auto)
  --job-root <path>            Override the parent directory of <profile>/<job_name>
  --config <path>              Carafe configuration file (default: config/carafe.cfg)
  --set KEY=VALUE              Override a config value; repeatable
  --include-entrapment-hits    Keep entrapment-only target hits in the Carafe report
  --refresh                    Update metadata, transfer scripts and a changed staged report
  --refresh-metadata           Update metadata only; preserve an already used staged report
  --test                       Validate and print the resolved plan without writing a job
  -h, --help                   Show this help

Examples:
  bash prepare_carafe_job.sh \
    --source-exp combined_md48_lysin_dmt_fixed_no_entrap \
    --profile balanced \
    --name carafe_v1 \
    --pipeline-version 2_5_0

  bash prepare_carafe_job.sh \
    --source-exp combined_md48_lysin_dmt_fixed_no_entrap \
    --profile balanced \
    --name carafe_rt_only \
    --set CARAFE_TUNE_TYPE=rt

  # Semi-specific Carafe2 is the workflow default; this explicitly records it
  # in a newly prepared job.
  bash prepare_carafe_job.sh \
    --source-exp <semi_specific_experiment> \
    --profile balanced \
    --name carafe_semi_v1 \
    --set CARAFE_SEMI_SPECIFIC=1

  # Re-copy the final library before every DIA-NN search instead of reusing a
  # local copy from an earlier search.
  bash prepare_carafe_job.sh \
    --source-exp <experiment> \
    --profile balanced \
    --set CARAFE_RECOPY_LIBRARY=1
EOF
}

die() {
  echo "ERROR: $*" >&2
  exit 1
}

info() {
  echo "INFO: $*"
}

warn() {
  echo "WARN: $*" >&2
}

yaml_quote() {
  local value="$1"
  value="${value//\'/\'\'}"
  printf "'%s'" "$value"
}

require_safe_name() {
  local label="$1"
  local value="$2"
  [[ "$value" =~ ^[A-Za-z0-9._-]+$ ]] || die "${label} contains unsupported characters: ${value}"
}

require_bool() {
  local key="$1"
  local value="$2"
  [[ "$value" == "0" || "$value" == "1" ]] || die "${key} must be 0 or 1, got '${value}'"
}

write_transfer_scripts() {
  local source_job_dir="$1"
  local transfer_script="$source_job_dir/meta/transfer_to_gpu.sh"
  local return_script="$source_job_dir/meta/return_carafe_result.sh"
  local pipeline_root_abs

  pipeline_root_abs="$(cd "$PIPELINE_ROOT" && pwd)"

  {
    echo '#!/usr/bin/env bash'
    echo 'set -euo pipefail'
    echo
    echo '# Generated by prepare_carafe_job.sh. The job is already on the shared filesystem.'
    printf 'SHARED_JOB_DIR=%q\n' "$source_job_dir"
    cat <<'EOF'

[[ -d "$SHARED_JOB_DIR" ]] || {
  echo "Shared Carafe job is missing: $SHARED_JOB_DIR" >&2
  exit 1
}
[[ -f "$SHARED_JOB_DIR/input/diann_step2_report.parquet" ]] || {
  echo "Shared Step-2 report is missing." >&2
  exit 1
}
[[ -f "$SHARED_JOB_DIR/meta/fasta_source_path.txt" ]] || {
  echo "Shared FASTA path metadata is missing." >&2
  exit 1
}
[[ -f "$(<"$SHARED_JOB_DIR/meta/fasta_source_path.txt")" ]] || {
  echo "Shared FASTA is not accessible from this machine: $(<"$SHARED_JOB_DIR/meta/fasta_source_path.txt")" >&2
  exit 1
}
while IFS= read -r raw; do
  [[ -f "$raw" ]] || { echo "Shared mzML is not accessible: $raw" >&2; exit 1; }
done < "$SHARED_JOB_DIR/meta/train_mzml_source_paths.txt"

echo "Shared Carafe job is ready; no rsync is required: $SHARED_JOB_DIR"
EOF
  } > "$transfer_script"

  {
    echo '#!/usr/bin/env bash'
    echo 'set -euo pipefail'
    echo
    echo '# Generated by prepare_carafe_job.sh. Carafe output is already shared.'
    printf 'SHARED_JOB_DIR=%q\n' "$source_job_dir"
    printf 'PIPELINE_ROOT=%q\n' "$pipeline_root_abs"
    cat <<'EOF'

[[ -d "$SHARED_JOB_DIR/carafe_output" ]] || {
  echo "Carafe output directory is missing: $SHARED_JOB_DIR/carafe_output" >&2
  exit 1
}

CHECK_ONLY=0
FORWARD_ARGS=()
for arg in "$@"; do
  case "$arg" in
    --check-only) CHECK_ONLY=1 ;;
    *) FORWARD_ARGS+=("$arg") ;;
  esac
done

if [[ -f "$SHARED_JOB_DIR/meta/carafe_library_path.txt" ]]; then
  LIBRARY_PATH="$(<"$SHARED_JOB_DIR/meta/carafe_library_path.txt")"
else
  mapfile -t LIBRARIES < <(find "$SHARED_JOB_DIR/carafe_output" -maxdepth 1 -type f -name '*.parquet' -printf '%p\n' 2>/dev/null | sort)
  (( ${#LIBRARIES[@]} == 1 )) || {
    echo "Expected one Carafe parquet library in $SHARED_JOB_DIR/carafe_output, found ${#LIBRARIES[@]}" >&2
    exit 1
  }
  LIBRARY_PATH="${LIBRARIES[0]}"
fi
[[ -f "$LIBRARY_PATH" ]] || {
  echo "Carafe library is missing: $LIBRARY_PATH" >&2
  exit 1
}

echo "Carafe output is already available to both machines: $SHARED_JOB_DIR/carafe_output"
echo "Carafe library is ready: $LIBRARY_PATH"

if [[ "$CHECK_ONLY" == "1" ]]; then
  echo "Check-only mode: skipping final DIA-NN search."
  exit 0
fi

exec bash "$PIPELINE_ROOT/run_carafe_final_search.sh" --job "$SHARED_JOB_DIR" "${FORWARD_ARGS[@]}"
EOF
  } > "$return_script"

  chmod +x "$transfer_script" "$return_script"
}

extract_last_step_command() {
  local startcmd="$1"
  local script_name="$2"
  local profile="$3"
  local out_sub="${4:-}"

  awk -v script_name="$script_name" -v profile="$profile" -v out_sub="$out_sub" '
    index($0, script_name) {
      profile_match = (profile == "")
      out_sub_match = (out_sub == "")
      for (i = 1; i <= NF; i++) {
        if ($i == "--profile" && $(i + 1) == profile) profile_match = 1
        if ($i == "--out-sub" && $(i + 1) == out_sub) out_sub_match = 1
      }
      if (profile_match && out_sub_match) result = $0
    }
    END { print result }
  ' "$startcmd"
}

extract_option() {
  local command="$1"
  local option="$2"
  awk -v option="$option" '
    {
      for (i = 1; i <= NF; i++) {
        if ($i == option) {
          print $(i + 1)
          exit
        }
      }
    }
  ' <<<"$command"
}

extract_repeated_option() {
  local command="$1"
  local option="$2"
  awk -v option="$option" '
    {
      for (i = 1; i <= NF; i++) {
        if ($i == option) print $(i + 1)
      }
    }
  ' <<<"$command"
}

extract_run_all_command() {
  local file="$1"
  awk '/run_all\.sh/ { line = $0 } END { print line }' "$file"
}

extract_last_non_comment_line() {
  local file="$1"
  awk '
    /^[[:space:]]*#/ { next }
    /^[[:space:]]*$/ { next }
    { line = $0 }
    END { print line }
  ' "$file"
}

extract_set_value() {
  local command="$1"
  local target_key="$2"
  awk -v target_key="$target_key" '
    {
      for (i = 1; i <= NF; i++) {
        if ($i != "--set") continue
        split($(i + 1), pair, "=")
        if (pair[1] == target_key) value = substr($(i + 1), length(target_key) + 2)
      }
    }
    END { print value }
  ' <<<"$command"
}

write_file_metadata() {
  local output="$1"
  local role="$2"
  local path="$3"
  local hash_file="$4"
  local size mtime digest=""

  size="$(stat -c '%s' "$path")"
  mtime="$(stat -c '%y' "$path")"
  if [[ "$hash_file" == "1" ]]; then
    digest="$(sha256sum "$path" | awk '{print $1}')"
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$role" "$path" "$size" "$mtime" "$digest" >> "$output"
}

CARAFE_CONFIG="$PIPELINE_ROOT/config/carafe.cfg"
ARGS=("$@")
for ((i = 0; i < ${#ARGS[@]}; i++)); do
  case "${ARGS[$i]}" in
    --config)
      ((i += 1))
      CARAFE_CONFIG="${ARGS[$i]:-}"
      [[ -n "$CARAFE_CONFIG" ]] || die "--config needs a path"
      ;;
    --config=*)
      CARAFE_CONFIG="${ARGS[$i]#*=}"
      ;;
  esac
done

source "$PIPELINE_ROOT/config/paths.cfg"
source "$PIPELINE_ROOT/config/defaults.cfg"
[[ -f "$CARAFE_CONFIG" ]] || die "Carafe config not found: $CARAFE_CONFIG"
source "$CARAFE_CONFIG"

SOURCE_EXP=""
PROFILE=""
JOB_NAME="carafe"
SOURCE_VERSION="auto"
TEST_MODE=0
REFRESH_MODE=0
REFRESH_METADATA_ONLY=0
INCLUDE_ENTRAPMENT_HITS=0
CLI_OVERRIDES=()

for ((i = 0; i < ${#ARGS[@]}; i++)); do
  case "${ARGS[$i]}" in
    --source-exp|--expname)
      ((i += 1))
      SOURCE_EXP="${ARGS[$i]:-}"
      [[ -n "$SOURCE_EXP" ]] || die "${ARGS[$((i - 1))]} needs a value"
      ;;
    --profile)
      ((i += 1))
      PROFILE="${ARGS[$i]:-}"
      [[ -n "$PROFILE" ]] || die "--profile needs a value"
      ;;
    --name)
      ((i += 1))
      JOB_NAME="${ARGS[$i]:-}"
      [[ -n "$JOB_NAME" ]] || die "--name needs a value"
      ;;
    --pipeline-version)
      ((i += 1))
      SOURCE_VERSION="${ARGS[$i]:-}"
      [[ -n "$SOURCE_VERSION" ]] || die "--pipeline-version needs a value"
      ;;
    --job-root)
      ((i += 1))
      CARAFE_JOB_ROOT="${ARGS[$i]:-}"
      [[ -n "$CARAFE_JOB_ROOT" ]] || die "--job-root needs a path"
      ;;
    --config|--config=*)
      if [[ "${ARGS[$i]}" == "--config" ]]; then
        ((i += 1))
      fi
      ;;
    --set)
      ((i += 1))
      override="${ARGS[$i]:-}"
      [[ "$override" == *=* ]] || die "--set expects KEY=VALUE"
      key_raw="${override%%=*}"
      key="${key_raw^^}"
      value="${override#*=}"
      [[ "$key" =~ ^[A-Z_][A-Z0-9_]*$ ]] || die "Invalid --set key '$key_raw' (use A-Z, a-z, 0-9, _)"
      printf -v "$key" '%s' "$value"
      CLI_OVERRIDES+=("$key")
      ;;
    --set=*)
      override="${ARGS[$i]#*=}"
      key_raw="${override%%=*}"
      key="${key_raw^^}"
      value="${override#*=}"
      [[ "$key" =~ ^[A-Z_][A-Z0-9_]*$ ]] || die "Invalid --set key '$key_raw' (use A-Z, a-z, 0-9, _)"
      printf -v "$key" '%s' "$value"
      CLI_OVERRIDES+=("$key")
      ;;
    --test)
      TEST_MODE=1
      ;;
    --include-entrapment-hits)
      INCLUDE_ENTRAPMENT_HITS=1
      ;;
    --refresh)
      REFRESH_MODE=1
      ;;
    --refresh-metadata)
      REFRESH_MODE=1
      REFRESH_METADATA_ONLY=1
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "Unknown argument: ${ARGS[$i]}"
      ;;
  esac
done

[[ -n "$SOURCE_EXP" ]] || die "--source-exp is required"
[[ -n "$PROFILE" ]] || die "--profile is required"
require_safe_name "source experiment" "$SOURCE_EXP"
require_safe_name "job name" "$JOB_NAME"

PROFILE="${PROFILE,,}"
case "$PROFILE" in
  balanced|fast|slow) ;;
  *) die "--profile must be balanced, fast, or slow" ;;
esac

case "$CARAFE_STAGE_MODE" in
  symlink|copy) ;;
  *) die "CARAFE_STAGE_MODE must be symlink or copy, got '$CARAFE_STAGE_MODE'" ;;
esac
require_bool "CARAFE_HASH_RAW_FILES" "$CARAFE_HASH_RAW_FILES"
require_bool "CARAFE_SHARED_INPUT_PATHS" "$CARAFE_SHARED_INPUT_PATHS"
require_bool "CARAFE_SEMI_SPECIFIC" "$CARAFE_SEMI_SPECIFIC"

SOURCE_DIR=""
SOURCE_VERSION_DIR=""
REPORT_NAME="tune_search_report_${PROFILE}.parquet"

# DIA-NN normally writes below OUTROOT, but read-only source experiments may
# also live in additional output roots (for example runs copied from another
# cluster).  The list is configured as a colon-separated value so paths can be
# added without changing the command-line interface.
SOURCE_OUTROOTS=("${OUTROOT%/}")
if [[ -n "${DIANN_ADDITIONAL_OUTROOTS:-}" ]]; then
  IFS=':' read -r -a additional_outroots <<< "$DIANN_ADDITIONAL_OUTROOTS"
  for additional_root in "${additional_outroots[@]}"; do
    [[ -n "$additional_root" ]] || continue
    additional_root="${additional_root%/}"
    [[ "$additional_root" == "${OUTROOT%/}" ]] && continue
    SOURCE_OUTROOTS+=("$additional_root")
  done
fi

is_below_source_outroot() {
  local path="$1"
  local root
  for root in "${SOURCE_OUTROOTS[@]}"; do
    [[ "$path" == "$root"/* ]] && return 0
  done
  return 1
}

if [[ "$SOURCE_VERSION" != "auto" ]]; then
  require_safe_name "pipeline version" "$SOURCE_VERSION"
  for source_root in "${SOURCE_OUTROOTS[@]}"; do
    candidate="${source_root}/${SOURCE_VERSION}/${SOURCE_EXP}"
    [[ -d "$candidate" ]] || continue
    [[ -f "$candidate/02_tunelib/$PROFILE/$REPORT_NAME" ]] || continue
    [[ -z "$SOURCE_DIR" ]] || die "Multiple matching source experiments found: $SOURCE_DIR $candidate"
    SOURCE_DIR="$candidate"
  done
  [[ -n "$SOURCE_DIR" ]] || die "Source experiment not found in: ${SOURCE_OUTROOTS[*]}"
  SOURCE_VERSION_DIR="$SOURCE_VERSION"
else
  candidates=()
  shopt -s nullglob
  for source_root in "${SOURCE_OUTROOTS[@]}"; do
    for candidate in "$source_root"/*/"$SOURCE_EXP"; do
      [[ -f "$candidate/02_tunelib/$PROFILE/$REPORT_NAME" ]] && candidates+=("$candidate")
    done
  done
  shopt -u nullglob
  if [[ ${#candidates[@]} -eq 0 ]]; then
    die "No source experiment with $REPORT_NAME found below: ${SOURCE_OUTROOTS[*]}; use --pipeline-version if needed"
  fi
  if [[ ${#candidates[@]} -gt 1 ]]; then
    die "Multiple matching source experiments found; pass --pipeline-version explicitly: ${candidates[*]}"
  fi
  SOURCE_DIR="${candidates[0]}"
  SOURCE_VERSION_DIR="$(basename "$(dirname "$SOURCE_DIR")")"
fi

STARTCMDS="$SOURCE_DIR/all_startcmds.txt"
STEP2_COMMAND=""
STEP5_COMMAND=""
STEP2_COMMAND_SOURCE="$STARTCMDS"
STEP5_COMMAND_SOURCE="$STARTCMDS"
TEST_MZMLS_SOURCE="recorded_step5"
TEST_DATASET_ID=""

if [[ -f "$STARTCMDS" ]]; then
  STEP2_COMMAND="$(extract_last_step_command "$STARTCMDS" "step2_tunelib.sh" "$PROFILE")"
  [[ -n "$STEP2_COMMAND" ]] || die "Could not find a recorded Step-2 command for profile '$PROFILE' in $STARTCMDS"
  STEP5_COMMAND="$(extract_last_step_command "$STARTCMDS" "step5_quant.sh" "" "baseline")"
else
  STEP2_STARTCMD="$SOURCE_DIR/02_tunelib/$PROFILE/startcmd_${PROFILE}.txt"
  [[ -f "$STEP2_STARTCMD" ]] || die "Missing source command record: expected either $STARTCMDS or $STEP2_STARTCMD"
  STEP2_COMMAND="$(extract_last_non_comment_line "$STEP2_STARTCMD")"
  [[ -n "$STEP2_COMMAND" ]] || die "Could not read DIA-NN Step-2 command from $STEP2_STARTCMD"
  STEP2_COMMAND_SOURCE="$STEP2_STARTCMD"
  STEP5_COMMAND_SOURCE=""
  warn "No all_startcmds.txt found; falling back to the recorded Step-2 command."
fi

# A Step-2-only export can still have an exact Step-5 comparison contract: its
# input library often belongs to a complete upstream run_all experiment. Walk
# up from that library and reuse that experiment's recorded baseline command.
# This preserves its DIA-NN version, modification preset and Step-5 switches.
if [[ -z "$STEP5_COMMAND" ]]; then
  STEP2_LIBRARY="$(extract_option "$STEP2_COMMAND" "--lib")"
  if [[ -n "$STEP2_LIBRARY" ]]; then
    baseline_parent="$(dirname "$STEP2_LIBRARY")"
    while is_below_source_outroot "$baseline_parent"; do
      baseline_startcmd="$baseline_parent/all_startcmds.txt"
      if [[ -f "$baseline_startcmd" ]]; then
        inferred_step5="$(extract_last_step_command "$baseline_startcmd" "step5_quant.sh" "" "baseline")"
        if [[ -n "$inferred_step5" ]]; then
          STEP5_COMMAND="$inferred_step5"
          STEP5_COMMAND_SOURCE="$baseline_startcmd (inferred from Step-2 library)"
          info "Using baseline Step-5 contract from $baseline_startcmd"
          break
        fi
      fi
      next_parent="$(dirname "$baseline_parent")"
      [[ "$next_parent" != "$baseline_parent" ]] || break
      baseline_parent="$next_parent"
    done
  fi
fi

SOURCE_MOD_CONFIG="$(extract_set_value "$STEP2_COMMAND" "MOD_CONFIG")"
if [[ -n "$SOURCE_MOD_CONFIG" && "$SOURCE_MOD_CONFIG" != "$CARAFE_TEMPLATE_MOD_CONFIG" ]]; then
  warn "Source uses MOD_CONFIG=${SOURCE_MOD_CONFIG}, but this Carafe config is templated for ${CARAFE_TEMPLATE_MOD_CONFIG}. Override the Carafe PTM settings before training."
fi

REPORT="$SOURCE_DIR/02_tunelib/$PROFILE/$REPORT_NAME"
FASTA="$(extract_option "$STEP2_COMMAND" "--fastaabs")"
if [[ -z "$FASTA" ]]; then
  FASTA="$(extract_option "$STEP2_COMMAND" "--fasta")"
fi
[[ -n "$FASTA" ]] || die "Could not resolve --fastaabs from the recorded Step-2 command"

# Cluster runs may retain an absolute --fastaabs path that is not mounted on
# analysis host.  Entrapment FASTAs are generated next to the run, while the
# original FASTA is kept in FASTABASE; prefer that original for Carafe.
RECORDED_FASTA="$FASTA"
ENTRAPMENT_SOURCE=0
if [[ "$(basename "$FASTA")" == *.entrapment*.fasta || "$STEP2_COMMAND" == *"--fasta-entrap"* ]]; then
  ENTRAPMENT_SOURCE=1
  original_fasta_name="$(basename "$FASTA")"
  original_fasta_name="${original_fasta_name%%.entrapment*}.fasta"
  fasta_candidates=(
    "$SOURCE_DIR/$original_fasta_name"
    "${FASTABASE%/}/$original_fasta_name"
  )
  FASTA=""
  for fasta_candidate in "${fasta_candidates[@]}"; do
    if [[ -f "$fasta_candidate" ]]; then
      FASTA="$fasta_candidate"
      break
    fi
  done
  [[ -n "$FASTA" ]] || die "Entrapment FASTA was found in the source metadata, but the original FASTA is missing; looked for: ${fasta_candidates[*]}"
elif [[ ! -f "$FASTA" ]]; then
  fasta_candidates=(
    "$SOURCE_DIR/$(basename "$FASTA")"
    "${FASTABASE%/}/$(basename "$FASTA")"
  )
  resolved_fasta=""
  for fasta_candidate in "${fasta_candidates[@]}"; do
    if [[ -f "$fasta_candidate" ]]; then
      resolved_fasta="$fasta_candidate"
      break
    fi
  done
  [[ -n "$resolved_fasta" ]] || die "Recorded FASTA is missing: $FASTA"
  FASTA="$resolved_fasta"
fi
[[ -f "$FASTA" ]] || die "Resolved FASTA is missing: $FASTA"
SHARED_FASTA="$FASTA"
if [[ "$CARAFE_SHARED_INPUT_PATHS" == "1" ]]; then
  SHARED_FASTA="${FASTABASE%/}/$(basename "$FASTA")"
  [[ -f "$SHARED_FASTA" ]] || die "Shared FASTA is missing: $SHARED_FASTA"
  cmp -s "$FASTA" "$SHARED_FASTA" || die "Shared FASTA differs from the source FASTA: $SHARED_FASTA"
fi

mapfile -t TRAIN_MZMLS < <(extract_repeated_option "$STEP2_COMMAND" "--f")
# A Step-2-only cluster export has no run_all command, but its exact training
# run IDs still identify one dataset declaration.  Infer it before resolving
# the held-out files, so relocated .raw inputs are handled like .mzML inputs.
DATASET_COMMAND="$(extract_run_all_command "$STARTCMDS")"
DATASET_ID="$(extract_option "$DATASET_COMMAND" "--ds")"
DATASET_SOURCE="$(extract_set_value "$DATASET_COMMAND" "DATASET_TYPE")"
if [[ -z "$DATASET_SOURCE" ]]; then
  DATASET_SOURCE="hunter"
fi
if [[ -z "$DATASET_ID" ]]; then
  TRAIN_MZML_LIST="$(mktemp)"
  trap 'rm -f "$TRAIN_MZML_LIST"' EXIT
  printf '%s\n' "${TRAIN_MZMLS[@]}" > "$TRAIN_MZML_LIST"
  DATASET_ID="$("${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/resolve_carafe_test_mzmls.py" \
    --inputs "$TRAIN_MZML_LIST" --datasets-dir "$SCRIPT_DIR/datasets" --dataset-id)"
  DATASET_SOURCE="$("${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/resolve_carafe_test_mzmls.py" \
    --inputs "$TRAIN_MZML_LIST" --datasets-dir "$SCRIPT_DIR/datasets" --source)"
  info "Inferred dataset '$DATASET_ID' (source '$DATASET_SOURCE') from the recorded Step-2 inputs."
fi
if [[ -n "$STEP5_COMMAND" ]]; then
  mapfile -t TEST_MZMLS < <(extract_repeated_option "$STEP5_COMMAND" "--f")
else
  TEST_MZMLS_SOURCE="dataset_metadata_relocated"
  TEST_DATASET_ID="$DATASET_ID"
  mapfile -t TEST_MZMLS < <("${CARAFE_PYTHON:-python3}" "$SCRIPT_DIR/bin/resolve_carafe_dataset_mzmls.py" \
    --dataset-id "$DATASET_ID" --source "$DATASET_SOURCE" --datasets-dir "$SCRIPT_DIR/datasets" \
    --data-root "$DATASET_ROOT" --split test)
  info "Resolved ${#TEST_MZMLS[@]} held-out acquisition files from dataset '$TEST_DATASET_ID'."
fi
(( ${#TRAIN_MZMLS[@]} > 0 )) || die "No training mzML files found in the recorded Step-2 command"

# A copied cluster run keeps the old absolute mzML paths in all_startcmds.txt.
# If any recorded input is unavailable, reconstruct the complete train/test
# set from the run's dataset declaration instead of guessing by filename.
all_paths_exist() {
  local path
  for path in "$@"; do
    [[ -f "$path" ]] || return 1
  done
}

# A copied cluster experiment may retain absolute input paths from its original
# storage root. Try progressively shorter suffixes against the current dataset
# root before falling back to a unique basename match.
relocate_recorded_paths() {
  local array_name="$1" index recorded relative candidate start
  local -n paths_ref="$array_name"
  local -a basename_candidates=() recorded_parts=()
  for index in "${!paths_ref[@]}"; do
    recorded="${paths_ref[$index]}"
    [[ -f "$recorded" ]] && continue
    candidate=""
    if [[ "$recorded" == /* ]]; then
      IFS='/' read -r -a recorded_parts <<< "${recorded#/}"
      for ((start=0; start<${#recorded_parts[@]}; start++)); do
        relative="${recorded_parts[*]:start}"
        candidate="${DATASET_ROOT%/}/$relative"
        [[ -f "$candidate" ]] && break
        candidate=""
      done
    fi
    if [[ -z "$candidate" ]]; then
      mapfile -t basename_candidates < <(find "$DATASET_ROOT" -type f -name "$(basename "$recorded")" -print 2>/dev/null)
      [[ ${#basename_candidates[@]} -eq 1 ]] && candidate="${basename_candidates[0]}"
    fi
    if [[ -n "$candidate" ]]; then
      paths_ref[$index]="$candidate"
      info "Relocated recorded cluster input: $recorded -> $candidate"
    fi
  done
}

